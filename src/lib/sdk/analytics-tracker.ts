/**
 * Generates `lib/ne-analytics.ts` — the analytics tracker pasted into a
 * client site's repo by the v3 SDK (Analytics v2 plan, Phase 1 items 1–5).
 *
 * The tracker lives in its own file (not in `lib/cms.ts`) so it can be
 * re-pushed without touching CMS fetch code; `lib/cms.ts` v3 re-exports
 * `installAnalytics` / `trackEvent` / `trackPageView` from it so existing
 * imports keep working.
 *
 * What v3 fixes and adds over the v1 tracker embedded in `lib/cms.ts`:
 * - **No duplicate page views.** v1 hooked `history.replaceState`, which
 *   Next.js calls on load and during navigations with an unchanged URL, and
 *   had no install guard (React StrictMode runs effects twice). v3 installs
 *   once, only counts a navigation when `pathname + search` actually changed,
 *   de-dupes the same URL fired within 1 s, and treats `replaceState` as a
 *   navigation only when the *pathname* changes (so `router.replace('/x')` is
 *   still counted, but query-only rewrites such as live filter/search inputs
 *   are not).
 * - **Correct SPA referrer.** `document.referrer` never changes during
 *   client-side navigation, so v1 repeated the landing referrer on every page
 *   of a session. v3 sends it only for the first page view of the document;
 *   later navigations send the previous page's URL (the server treats a
 *   same-host referrer as internal).
 * - **Engagement.** A `page_leave` event on navigation / tab hide / unload
 *   carries `engaged_ms` (visible time with interaction in the last 10 s,
 *   sent as a delta since the last flush) and `scroll_pct` (max viewport
 *   bottom reached, %).
 * - **Audience fields.** `is_entry`, `is_new_visitor`, `screen_w`, `lang`,
 *   and `tv` (tracker version) on every event.
 * - **Attribution.** On the session's first page view (or any page view whose
 *   URL carries campaign parameters) the tracker records `utm_*`, which ad
 *   click ID is present (`click_id_type`, never its value), `landing_path` and
 *   `session_referrer` in sessionStorage, and attaches them to every event in
 *   the session. The server derives the channel from them.
 * - **Batching.** Events are queued and sent to `…/analytics/batch` (≤ 20
 *   per request, 1 s debounce), with `navigator.sendBeacon` on unload. Bodies
 *   are `text/plain` so no CORS preflight is needed.
 * - **Privacy controls.** `disableAnalytics()` / `enableAnalytics()`
 *   (`localStorage.ne_optout = '1'`), optional `respectDNT` (DNT / Global
 *   Privacy Control) and a `consent()` gate. No cookies, no fingerprinting:
 *   the visitor ID is a random ID in localStorage.
 * - Local development hosts (localhost, 127.0.0.1, *.local) are not tracked
 *   unless `trackLocalhost: true`.
 *
 * The generated code avoids template literals so this generator only has
 * two interpolation points (CMS base URL and client slug), both emitted via
 * `JSON.stringify`.
 */
export const ANALYTICS_TRACKER_VERSION = 3;

export function generateAnalyticsTracker(slug: string, cmsBase: string): string {
  return `// lib/ne-analytics.ts - generated by NE Website Manager (analytics tracker v${ANALYTICS_TRACKER_VERSION})
//
// First-party, cookieless page analytics for this site. Call
// installAnalytics() once in the browser (e.g. from a client component in the
// root layout). Visitors can opt out with disableAnalytics(), or by setting
// localStorage.ne_optout = '1'. Regenerate this file from the CMS
// (Settings -> Integration) rather than editing it by hand.

const CMS_BASE = ${JSON.stringify(cmsBase)};
const CLIENT_SLUG = ${JSON.stringify(slug)};
const ENDPOINT = CMS_BASE + '/api/client/' + CLIENT_SLUG + '/analytics/batch';

export const ANALYTICS_TRACKER_VERSION = ${ANALYTICS_TRACKER_VERSION};

export type AnalyticsMetadata = Record<string, string | number | boolean | null>;

export interface InstallAnalyticsOptions {
  /** Do not track visitors whose browser sends Do Not Track or Global Privacy Control. Default false. */
  respectDNT?: boolean;
  /** Called before every event; return false to suppress tracking (e.g. until cookie-banner consent). */
  consent?: () => boolean;
  /** Also track on localhost / 127.0.0.1 / *.local. Default false. */
  trackLocalhost?: boolean;
}

type Payload = Record<string, unknown>;
type Queued = { payload: Payload; at: number };
type PageState = { path: string; engagedMs: number; sentMs: number; maxScroll: number; sentScroll: number };

const OPTOUT_KEY = 'ne_optout';
const VISITOR_KEY = 'ne_visitor_id';
const SESSION_KEY = 'ne_session_id';
const NEW_VISITOR_KEY = 'ne_visitor_new';
const ENTRY_KEY = 'ne_entry_sent';
const ATTRIBUTION_KEY = 'ne_attribution';
const UTM_PARAMS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content'];
const CLICK_ID_PARAMS = ['gclid', 'gbraid', 'wbraid', 'msclkid', 'dclid', 'fbclid', 'ttclid', 'li_fat_id', 'twclid'];
const ENGAGE_WINDOW_MS = 10000;
const DEDUPE_MS = 1000;
const FLUSH_DELAY_MS = 1000;
const MAX_BATCH = 20;

let installed = false;
let options: InstallAnalyticsOptions = {};
let queue: Queued[] = [];
let flushTimer: ReturnType<typeof setTimeout> | undefined;
const memory: Record<string, string> = {};

let page: PageState | null = null;
let currentKey = '';
let currentUrl: string | null = null;
let lastView = { key: '', at: 0 };
let lastActivity = 0;
let lastTick = 0;

function store(kind: 'local' | 'session'): Storage | null {
  try {
    return kind === 'local' ? window.localStorage : window.sessionStorage;
  } catch {
    return null;
  }
}

function read(kind: 'local' | 'session', key: string): string | null {
  try {
    const value = store(kind)?.getItem(key);
    if (value !== null && value !== undefined) return value;
  } catch {
    // Storage blocked (privacy mode, sandboxed iframe) - fall back to memory.
  }
  return memory[kind + ':' + key] ?? null;
}

function write(kind: 'local' | 'session', key: string, value: string | null) {
  if (value === null) delete memory[kind + ':' + key];
  else memory[kind + ':' + key] = value;
  try {
    const s = store(kind);
    if (!s) return;
    if (value === null) s.removeItem(key);
    else s.setItem(key, value);
  } catch {
    // Ignore quota / blocked storage.
  }
}

function randomId(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  return Math.random().toString(36).slice(2) + Date.now().toString(36);
}

function identity() {
  let visitorId = read('local', VISITOR_KEY);
  let createdVisitor = false;
  if (!visitorId) {
    visitorId = randomId();
    createdVisitor = true;
    write('local', VISITOR_KEY, visitorId);
  }
  let sessionId = read('session', SESSION_KEY);
  if (!sessionId) {
    sessionId = randomId();
    write('session', SESSION_KEY, sessionId);
    write('session', NEW_VISITOR_KEY, createdVisitor ? '1' : '0');
  }
  const isNewVisitor = createdVisitor || read('session', NEW_VISITOR_KEY) === '1';
  return { visitorId, sessionId, isNewVisitor };
}

function isLocalHost(): boolean {
  const h = window.location.hostname;
  return h === 'localhost' || h === '127.0.0.1' || h === '[::1]' || h === '' || h.endsWith('.local');
}

function allowed(): boolean {
  if (typeof window === 'undefined') return false;
  if (read('local', OPTOUT_KEY) === '1') return false;
  if (!options.trackLocalhost && isLocalHost()) return false;
  if (options.respectDNT) {
    const nav = navigator as Navigator & { globalPrivacyControl?: boolean };
    if (nav.doNotTrack === '1' || nav.globalPrivacyControl === true) return false;
  }
  if (options.consent) {
    try {
      if (!options.consent()) return false;
    } catch {
      return false;
    }
  }
  return true;
}

function attribution(): Payload {
  try {
    const raw = read('session', ATTRIBUTION_KEY);
    return raw ? (JSON.parse(raw) as Payload) : {};
  } catch {
    return {};
  }
}

function captureAttribution(isEntry: boolean, referrer: string | null) {
  let params: URLSearchParams;
  try {
    params = new URLSearchParams(window.location.search);
  } catch {
    return;
  }
  const found: Payload = {};
  let campaign = false;
  for (const key of UTM_PARAMS) {
    const value = params.get(key);
    if (value) {
      found[key] = value.slice(0, 100);
      campaign = true;
    }
  }
  for (const key of CLICK_ID_PARAMS) {
    if (params.has(key)) {
      found.click_id_type = key;
      campaign = true;
      break;
    }
  }
  if (!isEntry && !campaign) return;
  found.landing_path = window.location.pathname;
  found.session_referrer = referrer;
  write('session', ATTRIBUTION_KEY, JSON.stringify(found));
}

function basePayload(eventName: string): Payload {
  const id = identity();
  return {
    ...attribution(),
    event_name: eventName,
    path: window.location.pathname,
    title: document.title,
    visitor_id: id.visitorId,
    session_id: id.sessionId,
    is_new_visitor: id.isNewVisitor,
    tv: ANALYTICS_TRACKER_VERSION,
    screen_w: window.screen ? window.screen.width : null,
    lang: navigator.language || null,
  };
}

function send(body: string, useBeacon: boolean) {
  if (useBeacon && typeof navigator.sendBeacon === 'function') {
    try {
      if (navigator.sendBeacon(ENDPOINT, new Blob([body], { type: 'text/plain' }))) return;
    } catch {
      // Fall through to fetch.
    }
  }
  fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'Content-Type': 'text/plain' },
    body,
    keepalive: true,
  }).catch(() => undefined);
}

function flush(useBeacon = false) {
  if (flushTimer !== undefined) {
    clearTimeout(flushTimer);
    flushTimer = undefined;
  }
  const now = Date.now();
  while (queue.length > 0) {
    const batch = queue.splice(0, MAX_BATCH).map((q) => ({ ...q.payload, age_ms: Math.max(0, now - q.at) }));
    send(JSON.stringify({ events: batch }), useBeacon);
  }
}

function enqueue(payload: Payload) {
  if (!allowed()) return;
  queue.push({ payload, at: Date.now() });
  if (queue.length >= MAX_BATCH) flush();
  else if (flushTimer === undefined) flushTimer = setTimeout(() => flush(), FLUSH_DELAY_MS);
}

function scrollPercent(): number {
  const doc = document.documentElement;
  const height = Math.max(doc.scrollHeight, document.body ? document.body.scrollHeight : 0);
  if (height <= 0) return 100;
  const bottom = (window.scrollY || doc.scrollTop || 0) + window.innerHeight;
  return Math.max(0, Math.min(100, Math.round((bottom / height) * 100)));
}

function tick() {
  const now = Date.now();
  if (page && document.visibilityState === 'visible' && now - lastActivity < ENGAGE_WINDOW_MS) {
    // Capped so a throttled/suspended timer can't credit a long gap at once.
    page.engagedMs += Math.min(Math.max(0, now - lastTick), 5000);
  }
  lastTick = now;
}

function onActivity() {
  lastActivity = Date.now();
}

function onScroll() {
  lastActivity = Date.now();
  if (page) page.maxScroll = Math.max(page.maxScroll, scrollPercent());
}

function startPage() {
  const now = Date.now();
  page = { path: window.location.pathname, engagedMs: 0, sentMs: 0, maxScroll: scrollPercent(), sentScroll: -1 };
  lastActivity = now;
  lastTick = now;
}

function flushLeave() {
  if (!page) return;
  tick();
  const delta = page.engagedMs - page.sentMs;
  if (delta <= 0 && page.maxScroll === page.sentScroll) return;
  const payload = basePayload('page_leave');
  payload.path = page.path;
  delete payload.title;
  payload.engaged_ms = delta;
  payload.scroll_pct = page.maxScroll;
  page.sentMs = page.engagedMs;
  page.sentScroll = page.maxScroll;
  enqueue(payload);
}

function recordPageView(metadata: AnalyticsMetadata, referrer: string | null) {
  if (!allowed()) return;
  const key = window.location.pathname + window.location.search;
  const now = Date.now();
  if (key === lastView.key && now - lastView.at < DEDUPE_MS) return;
  lastView = { key, at: now };

  const isEntry = read('session', ENTRY_KEY) !== '1';
  if (isEntry) write('session', ENTRY_KEY, '1');
  captureAttribution(isEntry, referrer);
  const payload = basePayload('page_view');
  payload.is_entry = isEntry;
  payload.referrer = referrer;
  payload.metadata = metadata;
  enqueue(payload);
  if (installed) startPage();
  currentUrl = window.location.origin + window.location.pathname;
}

function onUrlChange(pathnameOnly: boolean) {
  const key = window.location.pathname + window.location.search;
  if (key === currentKey) return;
  const pathChanged = currentKey.split('?')[0] !== window.location.pathname;
  if (pathnameOnly && !pathChanged) return;
  currentKey = key;
  const referrer = currentUrl;
  flushLeave();
  page = null;
  // Next.js updates document.title after the URL change, so read it a tick later.
  setTimeout(() => recordPageView({}, referrer), 0);
}

function onHide() {
  flushLeave();
  flush(true);
}

/** Records a custom event, e.g. trackEvent('contact_click', { location: 'footer' }). */
export function trackEvent(eventName: string, metadata: AnalyticsMetadata = {}): Promise<void> {
  if (typeof window === 'undefined') return Promise.resolve();
  const payload = basePayload(eventName);
  payload.metadata = metadata;
  enqueue(payload);
  return Promise.resolve();
}

/**
 * Records a page view for the current URL. installAnalytics() already does
 * this on load and on every client-side navigation - only call it yourself if
 * you are not using installAnalytics().
 */
export function trackPageView(metadata: AnalyticsMetadata = {}): Promise<void> {
  if (typeof window === 'undefined') return Promise.resolve();
  recordPageView(metadata, currentUrl ?? (document.referrer || null));
  return Promise.resolve();
}

/** Starts automatic page-view and engagement tracking. Safe to call more than once. */
export function installAnalytics(opts: InstallAnalyticsOptions = {}) {
  if (typeof window === 'undefined' || installed) return;
  installed = true;
  options = opts;

  currentKey = window.location.pathname + window.location.search;
  recordPageView({}, document.referrer || null);

  const originalPushState = history.pushState;
  const originalReplaceState = history.replaceState;
  history.pushState = function pushState(this: History, ...args: Parameters<History['pushState']>) {
    originalPushState.apply(this, args);
    onUrlChange(false);
  };
  history.replaceState = function replaceState(this: History, ...args: Parameters<History['replaceState']>) {
    originalReplaceState.apply(this, args);
    onUrlChange(true);
  };
  window.addEventListener('popstate', () => onUrlChange(false));

  const passive = { passive: true, capture: true };
  window.addEventListener('scroll', onScroll, passive);
  for (const type of ['pointerdown', 'pointermove', 'keydown', 'touchstart', 'wheel']) {
    window.addEventListener(type, onActivity, passive);
  }
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'hidden') onHide();
    else {
      lastTick = Date.now();
      lastActivity = Date.now();
    }
  });
  window.addEventListener('pagehide', onHide);
  setInterval(tick, 1000);
}

/** Stops tracking this browser (persisted in localStorage) and drops anything queued. */
export function disableAnalytics() {
  if (typeof window === 'undefined') return;
  write('local', OPTOUT_KEY, '1');
  queue = [];
}

/** Re-enables tracking after disableAnalytics(). */
export function enableAnalytics() {
  if (typeof window === 'undefined') return;
  write('local', OPTOUT_KEY, null);
}

/** True unless this browser has opted out. */
export function isAnalyticsEnabled(): boolean {
  return typeof window !== 'undefined' && read('local', OPTOUT_KEY) !== '1';
}
`;
}
